-- 알림(사이트 안 알림 종 + 디스코드 DM)에 필요한 테이블입니다. (PostgreSQL) 001, 007 다음에 실행됩니다.
-- 화면: 헤더 알림 종, 알림 화면(모바일), 프로필 설정 > 디스코드 알림
-- 같은 내용이 Supabase용 backend/migrations/sql/20261025_06/ 에도 있습니다. 둘을 함께 고칩니다.
-- 1) 알림: users 1 : N (받는 사람 기준)
--    문구는 저장하지 않고, type + 관련 요청으로 보여 줄 때 만듭니다. (문구를 고쳐도 DB는 그대로)
CREATE TABLE notification (
  notification_id   BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  user_id           BIGINT        NOT NULL,                       -- 받는 사람 (users)
  type              VARCHAR(30)   NOT NULL,                       -- 알림 종류 (아래 ck_notification_type)
  actor_id          BIGINT        NULL,                           -- 알림을 일으킨 사람 (예: 수락한 전문가). 닉네임은 보여 줄 때 가져옴
  request_id        BIGINT        NULL,                           -- 관련 협업 요청 (연구 제목·거절 사유·이동할 화면을 여기서 찾음)
  read_at           TIMESTAMPTZ   NULL,                           -- 읽은 때. 비어 있으면 안 읽음 (종 숫자)
  discord_status    VARCHAR(10)   NOT NULL  DEFAULT 'pending',    -- pending=보낼 예정 / sent=보냄 / failed=실패 / skipped=안 보냄(DM 끔·서버 미참가)
  discord_attempts  SMALLINT      NOT NULL  DEFAULT 0,            -- DM 보내기 시도 횟수
  discord_sent_at   TIMESTAMPTZ   NULL,                           -- DM을 보낸 때
  discord_error     VARCHAR(200)  NULL,                           -- 마지막 실패 이유
  created_at        TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_notification PRIMARY KEY (notification_id),
  CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_notification_actor FOREIGN KEY (actor_id) REFERENCES users(user_id) ON DELETE SET NULL,
  CONSTRAINT fk_notification_request FOREIGN KEY (request_id) REFERENCES collaboration_request(request_id) ON DELETE CASCADE,
  -- 정해진 값만 들어가게 DB에서도 한 번 더 막습니다. (협업공간 알림은 그때 종류를 추가)
  CONSTRAINT ck_notification_type CHECK (type IN (
    'request_received',   -- 전문가: 협업 요청이 왔어요
    'request_accepted',   -- 연구회원: 요청을 수락했어요
    'request_rejected',   -- 연구회원: 요청을 거절했어요
    'request_canceled',   -- 전문가: 연구회원이 요청을 취소했어요
    'request_expired',    -- 둘 다: 7일 동안 답이 없어 만료됐어요
    'collab_started'      -- 둘 다: 협업을 시작했어요
  )),
  CONSTRAINT ck_notification_discord_status CHECK (discord_status IN ('pending', 'sent', 'failed', 'skipped'))
);

-- 같은 사람에게 같은 요청으로 같은 종류의 알림은 한 번만 만들어요. (만료 처리가 두 번 돌아도 알림은 하나)
CREATE UNIQUE INDEX uq_notification_user_type_request ON notification (user_id, type, request_id)
  WHERE request_id IS NOT NULL;

CREATE INDEX idx_notification_user_created ON notification (user_id, created_at DESC);  -- 내 알림 목록 (최신순)
CREATE INDEX idx_notification_unread ON notification (user_id) WHERE read_at IS NULL;   -- 안 읽은 개수 (종 숫자)
CREATE INDEX idx_notification_discord_pending ON notification (created_at)
  WHERE discord_status = 'pending';                                                       -- 디스코드로 보낼 알림 찾기


-- 2) 알림 설정: users 1 : 1. 줄이 없으면 모두 기본값(켜짐·연결 안 됨)으로 봅니다.
--    끄면 디스코드 DM만 안 가고, 사이트 안 알림(종)은 항상 쌓입니다.
CREATE TABLE notification_setting (
  user_id             BIGINT        NOT NULL,
  discord_dm          BOOLEAN       NOT NULL  DEFAULT TRUE,   -- 디스코드 DM으로 받기
  notify_request      BOOLEAN       NOT NULL  DEFAULT TRUE,   -- 협업 요청 알림을 DM으로 받기
  notify_workspace    BOOLEAN       NOT NULL  DEFAULT TRUE,   -- 협업공간 알림을 DM으로 받기 (협업공간 기능 이후)
  discord_joined_at   TIMESTAMPTZ   NULL,                     -- LabBridge 디스코드 서버에 참가한 때. 비어 있으면 "연결 안 됨"
  discord_blocked_at  TIMESTAMPTZ   NULL,                     -- DM이 막혀 실패한 때. 다음 DM이 성공하면 비움
  created_at          TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at          TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_notification_setting PRIMARY KEY (user_id),
  CONSTRAINT fk_notification_setting_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

CREATE TRIGGER trg_notification_setting_updated_at BEFORE UPDATE ON notification_setting
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();