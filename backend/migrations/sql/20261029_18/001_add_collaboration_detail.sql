-- 2) 요청: 한 사람이 상대에게 맡기는 일. collaboration 1 : N
--    받는 사람은 항상 상대방이에요 (협업은 두 사람). 기한은 없어도 돼요.
CREATE TABLE collaboration_task (
  task_id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  collaboration_id    BIGINT        NOT NULL,                  -- 어느 협업
  requested_by        BIGINT        NOT NULL,                  -- 요청한 사람 (users.user_id)
  assignee            BIGINT        NOT NULL,                  -- 받은 사람 = 상대방 (users.user_id)
  content             VARCHAR(300)  NOT NULL,                  -- 요청 내용 (예: 1차 결과를 표로 정리해 주세요)
  due_date            DATE          NULL,                      -- 기한 (선택)
  status              VARCHAR(10)   NOT NULL  DEFAULT 'open',  -- 아래 ck_task_status
  closed_at           TIMESTAMPTZ   NULL,                      -- 완료·취소한 때
  source              VARCHAR(10)   NOT NULL  DEFAULT 'web',   -- 어디서 남겼나: web / discord
  discord_message_id  VARCHAR(30)   NULL,                      -- 채널에 남긴 안내 메시지 번호 (완료되면 그 메시지를 고쳐요)
  created_at          TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at          TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration_task PRIMARY KEY (task_id),
  CONSTRAINT fk_task_collaboration FOREIGN KEY (collaboration_id) REFERENCES collaboration(collaboration_id) ON DELETE CASCADE,
  CONSTRAINT fk_task_requested_by FOREIGN KEY (requested_by) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_assignee FOREIGN KEY (assignee) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_task_status CHECK (status IN (
    'open',      -- 진행 중 (받은 사람이 아직 안 함)
    'done',      -- 완료 (받은 사람이 [완료])
    'canceled'   -- 취소 (요청한 사람이 필요 없어져서 [취소])
  )),
  CONSTRAINT ck_task_closed CHECK ((status = 'open') = (closed_at IS NULL)),  -- 끝난 요청만 closed_at 이 있어요
  CONSTRAINT ck_task_people CHECK (requested_by <> assignee),                -- 나에게 요청할 수는 없어요
  CONSTRAINT ck_task_source CHECK (source IN ('web', 'discord'))
);

CREATE INDEX idx_task_collaboration ON collaboration_task (collaboration_id, status);   -- 협업 상세의 요청 목록
CREATE INDEX idx_task_assignee_open ON collaboration_task (assignee) WHERE status = 'open';  -- 협업 공간 "지금 할 일"

CREATE TRIGGER trg_collaboration_task_updated_at BEFORE UPDATE ON collaboration_task
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 3) 정한 것: 한 사람이 제안하고 상대가 동의하면 확정. collaboration 1 : N
--    확정된 결정은 고치지 않아요. 바꾸려면 새 결정을 올리고 replaces_id 로 예전 결정을 가리켜요.
CREATE TABLE collaboration_decision (
  decision_id         BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  collaboration_id    BIGINT        NOT NULL,                      -- 어느 협업
  proposed_by         BIGINT        NOT NULL,                      -- 제안한 사람 (users.user_id). 동의는 항상 상대방
  content             VARCHAR(300)  NOT NULL,                      -- 정한 내용 (예: 평가 지표는 F1으로 본다)
  status              VARCHAR(10)   NOT NULL  DEFAULT 'proposed',  -- 아래 ck_decision_status
  answered_at         TIMESTAMPTZ   NULL,                          -- 상대가 동의하거나 "다시 얘기해요"를 누른 때
  answer_note         VARCHAR(200)  NULL,                          -- "다시 얘기해요" 한 줄 이유 (선택)
  replaces_id         BIGINT        NULL,                          -- 이 결정이 바꾸는 예전 결정 (같은 협업)
  source              VARCHAR(10)   NOT NULL  DEFAULT 'web',       -- web / discord
  discord_message_id  VARCHAR(30)   NULL,                          -- 채널에 남긴 [동의] 버튼 메시지 번호
  created_at          TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at          TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration_decision PRIMARY KEY (decision_id),
  CONSTRAINT fk_decision_collaboration FOREIGN KEY (collaboration_id) REFERENCES collaboration(collaboration_id) ON DELETE CASCADE,
  CONSTRAINT fk_decision_proposed_by FOREIGN KEY (proposed_by) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT fk_decision_replaces FOREIGN KEY (replaces_id) REFERENCES collaboration_decision(decision_id) ON DELETE SET NULL,
  CONSTRAINT ck_decision_status CHECK (status IN (
    'proposed',   -- 제안됨 (상대 동의 기다림)
    'agreed',     -- 확정 (상대가 [동의])
    'declined',   -- 상대가 [다시 얘기해요]
    'withdrawn',  -- 제안한 사람이 [취소]
    'replaced'    -- 확정됐었지만 새 결정으로 바뀜 (지우지 않고 남겨요)
  )),
  -- 상대가 답한 결정(확정·거절, 확정 뒤 바뀐 것)만 answered_at 이 있어요
  CONSTRAINT ck_decision_answered CHECK ((status IN ('agreed', 'declined', 'replaced')) = (answered_at IS NOT NULL)),
  CONSTRAINT ck_decision_source CHECK (source IN ('web', 'discord'))
);

CREATE INDEX idx_decision_collaboration ON collaboration_decision (collaboration_id, status);  -- 협업 상세의 정한 것 목록

CREATE TRIGGER trg_collaboration_decision_updated_at BEFORE UPDATE ON collaboration_decision
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 4) 기간 연장 · 조기 완료 요청: 한 사람이 요청하고 상대가 확인. collaboration 1 : N (기록으로 남겨요)
--    취소·중단은 확인 없이 바로 되니까 여기가 아니라 collaboration 의 ended_by · end_reason 에 남아요.
CREATE TABLE collaboration_change (
  change_id         BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  collaboration_id  BIGINT        NOT NULL,                     -- 어느 협업
  kind              VARCHAR(10)   NOT NULL,                     -- extend(기간 연장) / complete(조기 완료)
  requested_by      BIGINT        NOT NULL,                     -- 요청한 사람. 확인은 항상 상대방
  old_end_date      DATE          NOT NULL,                     -- 요청할 때의 종료일 (연장 기록용: 12.31 → 1.16)
  new_end_date      DATE          NULL,                         -- 연장할 새 종료일 (조기 완료는 비어 있어요)
  reason            VARCHAR(300)  NULL,                         -- 사유 (연장은 필수, 조기 완료는 선택)
  status            VARCHAR(10)   NOT NULL  DEFAULT 'pending',  -- 아래 ck_change_status
  answer_note       VARCHAR(200)  NULL,                         -- 거절할 때 한 줄 이유 (선택)
  expires_at        TIMESTAMPTZ   NOT NULL  DEFAULT now() + INTERVAL '3 days',  -- 3일 안에 답이 없으면 만료
  answered_at       TIMESTAMPTZ   NULL,                         -- 수락·거절·철회·만료된 때
  created_at        TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration_change PRIMARY KEY (change_id),
  CONSTRAINT fk_change_collaboration FOREIGN KEY (collaboration_id) REFERENCES collaboration(collaboration_id) ON DELETE CASCADE,
  CONSTRAINT fk_change_requested_by FOREIGN KEY (requested_by) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_change_kind CHECK (kind IN ('extend', 'complete')),
  CONSTRAINT ck_change_status CHECK (status IN (
    'pending',    -- 상대 확인 기다림
    'accepted',   -- 상대가 [수락] → 종료일이 바뀌거나 완료돼요
    'declined',   -- 상대가 [다시 얘기해요]
    'withdrawn',  -- 요청한 사람이 [철회]
    'expired'     -- 3일 동안 답이 없어 사라짐
  )),
  -- 연장: 새 종료일이 원래보다 뒤 + 사유 필수 / 조기 완료: 새 종료일 없음
  CONSTRAINT ck_change_extend CHECK (
    (kind = 'extend' AND new_end_date > old_end_date AND reason IS NOT NULL)
    OR (kind = 'complete' AND new_end_date IS NULL)
  ),
  CONSTRAINT ck_change_answered CHECK ((status = 'pending') = (answered_at IS NULL))
);

