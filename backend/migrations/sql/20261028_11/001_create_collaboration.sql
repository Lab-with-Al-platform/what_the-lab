-- 협업 공간과 일정 테이블을 공통 Supabase에 만듭니다. (alembic revision 20261028_11)
-- 화면: 협업 공간 (목록 · 전체 달력 · 협업 상세의 공유 달력)
-- Docker용 database/init/010_create_collaboration.sql 과 같은 내용입니다. 둘을 함께 고칩니다.

-- 1) 협업 공간: collaboration_request 1 : 1 (연구회원이 [협업 시작하기]를 누른 요청 하나 = 협업 하나)
--    연구 하나로 전문가 여러 명과 각각 1:1 협업하므로 research 1 : N, expert 1 : N 이에요.
--    연구회원은 research.user_id 로 알 수 있어서 따로 저장하지 않습니다. (collaboration_request 와 같은 방식)
CREATE TABLE collaboration (
  collaboration_id      BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  request_id            BIGINT        NOT NULL,                     -- 어느 요청에서 시작됐나 (collaboration_request)
  research_id           BIGINT        NOT NULL,                     -- 어떤 연구 (research)
  expert_id             BIGINT        NOT NULL,                     -- 함께하는 AI 전문가 (expert.user_id)
  start_date            DATE          NOT NULL,                     -- 시작일: 요청에서 확정된 기간을 복사 (조정했으면 조정한 기간)
  end_date              DATE          NOT NULL,                     -- 종료일: 연장하면 바뀌어요
  status                VARCHAR(20)   NOT NULL  DEFAULT 'ongoing',  -- ongoing / done / ended_early / canceled (아래 ck_collaboration_status)
  agreement             JSONB         NOT NULL,                     -- 시작할 때 합의한 내용 복사본 (연구 제목·분야·맡길 일·결과물·보상·미팅·데이터 조건)
  researcher_opened_at  TIMESTAMPTZ   NULL,                         -- 연구회원이 협업 공간을 처음 연 때 (비어 있으면 [협업 공간 열기])
  expert_opened_at      TIMESTAMPTZ   NULL,                         -- 전문가가 협업 공간을 처음 연 때
  ended_at              TIMESTAMPTZ   NULL,                         -- 완료·중도 종료·취소된 때
  created_at            TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at            TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration PRIMARY KEY (collaboration_id),
  CONSTRAINT uq_collaboration_request UNIQUE (request_id),         -- 요청 하나에 협업은 하나만
  -- 협업 기록이 남아 있으면 요청·연구·전문가를 지울 수 없게 막아요. (연구 삭제는 API에서도 막음)
  CONSTRAINT fk_collaboration_request FOREIGN KEY (request_id) REFERENCES collaboration_request(request_id) ON DELETE RESTRICT,
  CONSTRAINT fk_collaboration_research FOREIGN KEY (research_id) REFERENCES research(research_id) ON DELETE RESTRICT,
  CONSTRAINT fk_collaboration_expert FOREIGN KEY (expert_id) REFERENCES expert(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_collaboration_status CHECK (status IN (
    'ongoing',      -- 진행 중 (오늘 < 시작일이면 화면에서 "시작 전"으로 보여요)
    'done',         -- 완료 (종료일이 지나거나, 완료 요청을 상대가 확인)
    'ended_early',  -- 중도 종료 (이유 필수, 평가 있음)
    'canceled'      -- 시작 전 취소 (이유 필수, 평가 없음)
  )),
  CONSTRAINT ck_collaboration_period CHECK (end_date >= start_date),
  CONSTRAINT ck_collaboration_ended CHECK ((status = 'ongoing') = (ended_at IS NULL))  -- 끝난 협업만 ended_at 이 있어요
);

CREATE INDEX idx_collaboration_research ON collaboration (research_id);  -- 연구회원의 협업 목록 (research.user_id 로 이어서)
CREATE INDEX idx_collaboration_expert ON collaboration (expert_id);      -- 전문가의 협업 목록
CREATE INDEX idx_collaboration_ongoing_end ON collaboration (end_date) WHERE status = 'ongoing';  -- 종료일 지난 협업 자동 완료

CREATE TRIGGER trg_collaboration_updated_at BEFORE UPDATE ON collaboration
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 2) 일정: collaboration 1 : N (협업 상세의 공유 달력, 협업 공간 첫 화면의 전체 달력)
--    매주 반복 일정은 날짜마다 한 줄씩 만들고 series_id 로 묶어요. (하나만 고치거나 지우기 쉬워요)
CREATE TABLE collaboration_schedule (
  schedule_id       BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  collaboration_id  BIGINT        NOT NULL,                  -- 어느 협업 일정인가
  kind              VARCHAR(20)   NOT NULL,                  -- meeting / work / due / etc (아래 ck_schedule_kind)
  title             VARCHAR(60)   NOT NULL,                  -- 일정 제목 (예: 주간 미팅)
  start_date        DATE          NOT NULL,                  -- 날짜 (작업 기간이면 시작일)
  end_date          DATE          NOT NULL,                  -- 작업 기간의 끝날. 하루짜리 일정은 start_date 와 같아요
  start_time        TIME          NULL,                      -- 시작 시각 (미팅·기타, 선택)
  end_time          TIME          NULL,                      -- 끝 시각 (선택)
  place             VARCHAR(300)  NULL,                      -- 장소·링크 (예: 온라인 · 구글 미트 링크 / OO대 인문대 302호)
  memo              VARCHAR(500)  NULL,                      -- 메모 (선택)
  assignee          VARCHAR(10)   NULL,                      -- 작업 기간 담당: researcher / expert / 비어 있으면 함께
  series_id         BIGINT        NULL,                      -- 매주 반복으로 만든 일정 묶음 (첫 일정의 schedule_id)
  created_by        BIGINT        NOT NULL,                  -- 등록한 사람 (users.user_id)
  created_at        TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at        TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration_schedule PRIMARY KEY (schedule_id),
  CONSTRAINT fk_schedule_collaboration FOREIGN KEY (collaboration_id) REFERENCES collaboration(collaboration_id) ON DELETE CASCADE,
  CONSTRAINT fk_schedule_created_by FOREIGN KEY (created_by) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_schedule_kind CHECK (kind IN (
    'meeting',  -- 미팅
    'work',     -- 작업 기간 (여러 날)
    'due',      -- 결과물 마감
    'etc'       -- 기타
  )),
  CONSTRAINT ck_schedule_period CHECK (end_date >= start_date),
  CONSTRAINT ck_schedule_one_day CHECK (kind = 'work' OR end_date = start_date),  -- 여러 날은 작업 기간만
  CONSTRAINT ck_schedule_time CHECK (end_time IS NULL OR (start_time IS NOT NULL AND end_time > start_time)),
  CONSTRAINT ck_schedule_assignee CHECK (assignee IS NULL OR assignee IN ('researcher', 'expert'))
);

CREATE INDEX idx_schedule_collaboration_date ON collaboration_schedule (collaboration_id, start_date);  -- 협업별 달력
CREATE INDEX idx_schedule_series ON collaboration_schedule (series_id) WHERE series_id IS NOT NULL;     -- 반복 일정 한 번에 고치기

CREATE TRIGGER trg_collaboration_schedule_updated_at BEFORE UPDATE ON collaboration_schedule
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 3) 이미 [협업 시작하기]를 누른 요청은 협업 공간으로 옮겨요. (새 테이블을 만들기 전에 시작된 협업)
--    기간은 전문가가 조정했으면 조정한 기간, 합의 내용은 지금 연구 내용으로 채워요.
INSERT INTO collaboration (request_id, research_id, expert_id, start_date, end_date, agreement, created_at)
SELECT
  r.request_id,
  r.research_id,
  r.expert_id,
  COALESCE(r.accepted_start_date, r.start_date),
  COALESCE(r.accepted_end_date, r.end_date),
  jsonb_build_object(
    'title', rs.title,
    'description', rs.description,
    'field_ids', COALESCE((SELECT jsonb_agg(d.field_id ORDER BY d.field_id) FROM research_domain d WHERE d.research_id = rs.research_id), '[]'::jsonb),
    'able_work_ids', COALESCE((SELECT jsonb_agg(w.able_work_id ORDER BY w.able_work_id) FROM research_able_work w WHERE w.research_id = rs.research_id), '[]'::jsonb),
    'task_unsure', rs.task_unsure,
    'outputs', COALESCE((SELECT jsonb_agg(o.output_type ORDER BY o.output_type) FROM research_output o WHERE o.research_id = rs.research_id), '[]'::jsonb),
    'rewards', COALESCE((SELECT jsonb_agg(w.reward_type ORDER BY w.reward_type) FROM research_reward w WHERE w.research_id = rs.research_id), '[]'::jsonb),
    'data_types', COALESCE((SELECT jsonb_agg(t.data_type ORDER BY t.data_type) FROM research_data_type t WHERE t.research_id = rs.research_id), '[]'::jsonb),
    'data_status', rs.data_status,
    'share_policy', rs.share_policy,
    'share_condition', rs.share_condition,
    'meeting_type', rs.meeting_type,
    'face_to_area', rs.face_to_area,
    'message', r.message,
    'reply_message', r.reply_message
  ),
  COALESCE(r.started_at, now())
FROM collaboration_request r
JOIN research rs ON rs.research_id = r.research_id
WHERE r.status = 'started';