-- AI 전문가 내 이력(프로필)에 필요한 테이블입니다. (PostgreSQL) 001 다음에 실행됩니다.
-- 전문가 한 사람에게 딸린 표는 expert_ 로 시작합니다. (연구에 딸린 표는 research_)

-- 1) 연구 분야 대분류 기준표: 택소노미 v4 F01~F10 (데이터는 005 시드)
CREATE TABLE field_category (
  field_category_id  VARCHAR(10)  NOT NULL,                            -- 택소노미 대분류 ID (F01 ~ F10)
  name               VARCHAR(50)  NOT NULL,                            -- 화면 이름 (예: 의학·보건·약학)
  sort_order         INT          NOT NULL,                            -- 표시 순서
  status             VARCHAR(20)  NOT NULL  DEFAULT 'pending_review',  -- pending_review / active / retired
  taxonomy_ver       VARCHAR(10)  NOT NULL,                            -- 분류표 버전 (예: 4.0)
  CONSTRAINT pk_field_category PRIMARY KEY (field_category_id)
);

-- 2) 세부 연구 분야 기준표: 택소노미 v4 FIELD001~FIELD083 (데이터는 005 시드)
CREATE TABLE research_field (
  field_id           VARCHAR(10)  NOT NULL,                            -- 택소노미 FIELD ID (FIELD001 ~ FIELD083)
  field_category_id  VARCHAR(10)  NOT NULL,                            -- field_category.field_category_id
  name               VARCHAR(50)  NOT NULL,                            -- 화면 이름 (예: 의료영상·영상의학)
  sort_order         INT          NOT NULL,                            -- 대분류 안에서의 표시 순서
  status             VARCHAR(20)  NOT NULL  DEFAULT 'pending_review',  -- pending_review / active / retired
  taxonomy_ver       VARCHAR(10)  NOT NULL,                            -- 분류표 버전 (예: 4.0)
  CONSTRAINT pk_research_field PRIMARY KEY (field_id),
  CONSTRAINT fk_research_field_category FOREIGN KEY (field_category_id) REFERENCES field_category(field_category_id)
);

-- 3) 도메인: 전문가가 다뤄 본 연구 분야 (expert 1 : N, 최대 5개는 API에서 검사)
CREATE TABLE expert_domain (
  expert_domain_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  user_id           BIGINT       NOT NULL,
  field_id          VARCHAR(10)  NOT NULL,  -- research_field.field_id (예: FIELD011)
  CONSTRAINT pk_expert_domain PRIMARY KEY (expert_domain_id),
  CONSTRAINT uq_expert_domain UNIQUE (user_id, field_id),
  CONSTRAINT fk_expert_domain_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_expert_domain_field FOREIGN KEY (field_id) REFERENCES research_field(field_id)
);

-- 4) 협업 조건: expert 1 : 1
--    앞으로 만들 '협업 요청'과 헷갈리지 않게 expert_collab_condition 으로 씁니다.
CREATE TABLE expert_collab_condition (
  user_id         BIGINT       NOT NULL,
  meeting_type    VARCHAR(20)  NOT NULL,  -- online / offline_ok
  face_to_area    VARCHAR(50)  NULL,      -- 대면 가능 지역. 온라인만이면 NULL
  available_time  VARCHAR(20)  NOT NULL,  -- lt5 / 5_10 / gt10 (주당 가능 시간)
  created_at      TIMESTAMPTZ  NOT NULL  DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL  DEFAULT now(),
  CONSTRAINT pk_expert_collab_condition PRIMARY KEY (user_id),
  CONSTRAINT fk_expert_collab_condition_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE
);
CREATE TRIGGER trg_expert_collab_condition_updated_at BEFORE UPDATE ON expert_collab_condition
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 5) 희망 보상: expert 1 : N (여러 개 선택)
CREATE TABLE expert_reward (
  expert_reward_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  user_id           BIGINT       NOT NULL,
  reward_type       VARCHAR(20)  NOT NULL,  -- research_fund / authorship / undecided
  CONSTRAINT pk_expert_reward PRIMARY KEY (expert_reward_id),
  CONSTRAINT uq_expert_reward UNIQUE (user_id, reward_type),
  CONSTRAINT fk_expert_reward_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE
);

-- 6) 포트폴리오: expert 1 : N
CREATE TABLE portfolio (
  portfolio_id  BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  user_id       BIGINT        NOT NULL,
  title         VARCHAR(60)   NOT NULL,  -- 무엇을 만들었나요
  role          VARCHAR(200)  NOT NULL,  -- 내 역할
  pdf_url       VARCHAR(500)  NULL,      -- 올린 PDF의 저장 위치 (예: portfolios/abc123.pdf)
  created_at    TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at    TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_portfolio PRIMARY KEY (portfolio_id),
  CONSTRAINT fk_portfolio_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE
);
CREATE INDEX idx_portfolio_user ON portfolio (user_id);
CREATE TRIGGER trg_portfolio_updated_at BEFORE UPDATE ON portfolio
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 6-1) 포트폴리오에서 AI로 한 일: portfolio 1 : N
CREATE TABLE portfolio_able_work (
  portfolio_able_work_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  portfolio_id            BIGINT       NOT NULL,
  able_work_id            VARCHAR(10)  NOT NULL,  -- able_work.able_work_id (예: UG04)
  CONSTRAINT pk_portfolio_able_work PRIMARY KEY (portfolio_able_work_id),
  CONSTRAINT uq_portfolio_able_work UNIQUE (portfolio_id, able_work_id),
  CONSTRAINT fk_pf_work_portfolio FOREIGN KEY (portfolio_id) REFERENCES portfolio(portfolio_id) ON DELETE CASCADE,
  CONSTRAINT fk_pf_work_code FOREIGN KEY (able_work_id) REFERENCES able_work(able_work_id)
);

-- 6-2) 포트폴리오 사용 기술: portfolio 1 : N (자유 입력)
CREATE TABLE portfolio_skill (
  portfolio_skill_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  portfolio_id        BIGINT       NOT NULL,
  skill_name          VARCHAR(30)  NOT NULL,  -- 예: PyTorch
  CONSTRAINT pk_portfolio_skill PRIMARY KEY (portfolio_skill_id),
  CONSTRAINT uq_portfolio_skill UNIQUE (portfolio_id, skill_name),
  CONSTRAINT fk_pf_skill_portfolio FOREIGN KEY (portfolio_id) REFERENCES portfolio(portfolio_id) ON DELETE CASCADE
);

-- 7) 경력: expert 1 : N
CREATE TABLE career (
  career_id    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  user_id      BIGINT       NOT NULL,
  company      VARCHAR(50)  NULL,      -- 회사·기관명 (밝히기 싫으면 NULL)
  job          VARCHAR(50)  NOT NULL,  -- 직무
  start_month  CHAR(7)      NOT NULL,  -- 시작 연월 (YYYY-MM)
  end_month    CHAR(7)      NULL,      -- 종료 연월 (YYYY-MM). 재직 중이면 NULL
  created_at   TIMESTAMPTZ  NOT NULL  DEFAULT now(),
  CONSTRAINT pk_career PRIMARY KEY (career_id),
  CONSTRAINT fk_career_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE
);
CREATE INDEX idx_career_user ON career (user_id);

-- 8) 학력: expert 1 : N
CREATE TABLE education (
  education_id    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  user_id         BIGINT       NOT NULL,
  school          VARCHAR(50)  NOT NULL,  -- 학교
  major           VARCHAR(50)  NOT NULL,  -- 전공·학위 (예: 컴퓨터공학 석사)
  graduated_year  CHAR(4)      NULL,      -- 졸업 연도 (YYYY)
  created_at      TIMESTAMPTZ  NOT NULL  DEFAULT now(),
  CONSTRAINT pk_education PRIMARY KEY (education_id),
  CONSTRAINT fk_education_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE
);
CREATE INDEX idx_education_user ON education (user_id);

-- 9) 자격증: expert 1 : N
CREATE TABLE certificate (
  certificate_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
  user_id         BIGINT       NOT NULL,
  name            VARCHAR(50)  NOT NULL,  -- 자격증 이름
  issuer          VARCHAR(50)  NULL,      -- 발급 기관
  acquired_year   CHAR(4)      NULL,      -- 취득 연도 (YYYY)
  created_at      TIMESTAMPTZ  NOT NULL  DEFAULT now(),
  CONSTRAINT pk_certificate PRIMARY KEY (certificate_id),
  CONSTRAINT fk_certificate_expert FOREIGN KEY (user_id) REFERENCES expert(user_id) ON DELETE CASCADE
);
CREATE INDEX idx_certificate_user ON certificate (user_id);