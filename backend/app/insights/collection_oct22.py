def collected_drafts() -> list[Draft]:
    """출처 확인은 수집 단계입니다. 관리자 검토 완료 표시·점수는 넣지 않습니다."""
    result = []
    for item in RESEARCHED_ITEMS:
        result.append(
            Draft.model_validate(
                {
                    "kind": item["kind"],
                    "title": item["title"],
                    "slug": item["slug"],
                    "summary": item["summary"],
                    "research_field": item["field"],
                    "case_type": "research",
                    "source": {
                        "title": item["source_title"],
                        "doi": item["doi"],
                        "url": item["url"],
                        "access_level": "unknown",
                        "bibliography_checked": False,
                    },
                    "claims": [
                        {
                            "field": field,
                            "text": text,
                            "locator": item["locator"],
                            "verification": "needs_review",
                            "evidence_level": item["evidence"],
                        }
                        for field, text in zip(FIELDS, item["claims"], strict=True)
                    ],
                    "glossary": [
                        {"label": label, "definition": definition}
                        for label, definition in item["terms"]
                    ],
                }
            )
        )
    return result
