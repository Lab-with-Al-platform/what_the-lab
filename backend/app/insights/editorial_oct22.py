def claim_paragraphs(text: str) -> list[dict]:
    """수집 메모에 있던 해석·제안 표시도 실제 문단 유형으로 옮깁니다."""
    markers = {
        "[적용 제안]": "application",
        "[해석]": "interpretation",
        "[쉬운 비유]": "interpretation",
    }
    for marker, kind in markers.items():
        if marker in text:
            before, after = text.split(marker, 1)
            return ([{"kind": "body", "text": before.strip()}] if before.strip() else []) + [
                {"kind": kind, "text": after.strip()}
            ]
    return [{"kind": "body", "text": text}]


