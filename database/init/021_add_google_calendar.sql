-- 구글 캘린더 연동 칸 + 일정 수정자·데이터 유형을 추가합니다. (PostgreSQL) 013 협업 테이블 다음에 실행됩니다.
-- 칸 추가는 Supabase용 backend/migrations/sql/20261028_17/ 과 같습니다. 아래 개정 번호만 Docker에 있습니다.

-- 1) 협업마다 구글 캘린더 하나 (누군가 처음 [구글 캘린더에 추가]를 누를 때 서버가 만들어요)
--    회원의 구글 이메일은 공유할 때 한 번만 쓰고 저장하지 않아요. "추가했는지"만 시각으로 남겨요.
ALTER TABLE collaboration
  ADD COLUMN google_calendar_id    VARCHAR(255)  NULL,  -- 구글 캘린더 번호 (예: abc123@group.calendar.google.com)
  ADD COLUMN researcher_google_at  TIMESTAMPTZ   NULL,  -- 연구회원이 자기 구글 캘린더에 추가한 때
  ADD COLUMN expert_google_at      TIMESTAMPTZ   NULL,  -- 전문가가 자기 구글 캘린더에 추가한 때
  ADD CONSTRAINT uq_collaboration_google_calendar UNIQUE (google_calendar_id);  -- 캘린더 하나 = 협업 하나

-- 2) 일정: 구글에 반영됐는지, 마지막으로 고친 사람, "데이터" 유형
--    구글 일정 번호는 따로 저장하지 않고 일정 번호로 정해요 (lbs + schedule_id). 그래서 지워도 찾을 수 있어요.
ALTER TABLE collaboration_schedule
  ADD COLUMN google_status    VARCHAR(10)   NOT NULL  DEFAULT 'none',  -- 아래 ck_schedule_google_status
  ADD COLUMN google_attempts  SMALLINT      NOT NULL  DEFAULT 0,       -- 구글 반영 시도 횟수
  ADD COLUMN google_error     VARCHAR(200)  NULL,                      -- 마지막 실패 이유
  ADD COLUMN updated_by       BIGINT        NULL,                      -- 마지막으로 고친 사람 (users.user_id)
  ADD CONSTRAINT ck_schedule_google_status CHECK (google_status IN (
    'none',     -- 구글 캘린더가 없는 협업 (반영할 곳 없음)
    'pending',  -- 구글에 반영할 차례 (새로 넣었거나 고침)
    'synced',   -- 구글과 같음
    'failed'    -- 여러 번 실패해서 멈춤 (이유는 google_error)
  )),
  ADD CONSTRAINT fk_schedule_updated_by FOREIGN KEY (updated_by) REFERENCES users(user_id) ON DELETE SET NULL;

ALTER TABLE collaboration_schedule DROP CONSTRAINT ck_schedule_kind;
ALTER TABLE collaboration_schedule ADD CONSTRAINT ck_schedule_kind CHECK (kind IN (
  'meeting',  -- 미팅
  'work',     -- 작업 기간
  'due',      -- 결과물 마감
  'data',     -- 데이터 전달·반납·삭제
  'etc'       -- 기타
));

CREATE INDEX idx_schedule_google_pending ON collaboration_schedule (schedule_id)
  WHERE google_status = 'pending';  -- 구글에 반영할 일정 찾기

-- 3) 지운 일정을 구글에서도 지우기 위한 대기열 (일정 줄은 이미 지워졌으니 따로 적어 둬요)
CREATE TABLE google_event_trash (
  trash_id     BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  calendar_id  VARCHAR(255)  NOT NULL,             -- 어느 구글 캘린더에서
  event_id     VARCHAR(64)   NOT NULL,             -- 어떤 구글 일정을 (lbs + schedule_id)
  attempts     SMALLINT      NOT NULL  DEFAULT 0,  -- 지우기 시도 횟수
  error        VARCHAR(200)  NULL,                 -- 마지막 실패 이유
  created_at   TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_google_event_trash PRIMARY KEY (trash_id)
);

