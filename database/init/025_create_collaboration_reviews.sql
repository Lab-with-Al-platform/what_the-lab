-- ACID-atomic install for a fresh Docker volume OR a carefully reviewed existing
-- local volume. The previous baseline must be 20261029_20. Never run on live Supabase.
BEGIN;
DO $version_guard$ BEGIN
  IF (SELECT version_num FROM public.insight_alembic_version LIMIT 1) IS DISTINCT FROM '20261029_20' THEN
    RAISE EXCEPTION 'Expected local schema baseline 20261029_20; abort review migration.';
  END IF;
  IF to_regclass('public.collaboration_review') IS NOT NULL THEN
    RAISE EXCEPTION 'Review table already exists; do not reapply.';
  END IF;
END $version_guard$;

-- WHAT THE LAB: verified collaboration-completion reviews.
-- Do not run against shared/production databases without a reviewed migration plan.
-- One review per side for each collaboration; no public client direct table access.
CREATE TABLE public.collaboration_review (
  review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collaboration_id BIGINT NOT NULL REFERENCES public.collaboration(collaboration_id) ON DELETE RESTRICT,
  reviewer_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
  reviewee_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
  reviewer_side VARCHAR(12) NOT NULL CHECK (reviewer_side IN ('researcher','expert')),
  expertise SMALLINT NOT NULL CHECK (expertise BETWEEN 1 AND 5),
  communication SMALLINT NOT NULL CHECK (communication BETWEEN 1 AND 5),
  timeliness SMALLINT NOT NULL CHECK (timeliness BETWEEN 1 AND 5),
  quality SMALLINT NOT NULL CHECK (quality BETWEEN 1 AND 5),
  comment VARCHAR(500) NOT NULL DEFAULT '',
  visibility VARCHAR(10) NOT NULL DEFAULT 'visible' CHECK (visibility IN ('visible','hidden')),
  edit_count SMALLINT NOT NULL DEFAULT 0 CHECK (edit_count BETWEEN 0 AND 1),
  revision_history JSONB NOT NULL DEFAULT '[]'::jsonb,
  moderation_reason VARCHAR(300),
  moderated_by BIGINT REFERENCES public.users(user_id) ON DELETE SET NULL,
  moderated_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_review_people CHECK (reviewer_id <> reviewee_id),
  CONSTRAINT uq_review_collaboration_side UNIQUE(collaboration_id,reviewer_side),
  CONSTRAINT uq_review_collaboration_reviewer UNIQUE(collaboration_id,reviewer_id)
);
CREATE INDEX idx_review_reviewee_visible ON public.collaboration_review(reviewee_id,created_at DESC)
  WHERE reviewer_side = 'researcher' AND visibility='visible';
CREATE INDEX idx_review_reviewer ON public.collaboration_review(reviewer_id,created_at DESC);

CREATE TABLE public.collaboration_review_report (
  report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id BIGINT NOT NULL REFERENCES public.collaboration_review(review_id) ON DELETE RESTRICT,
  reporter_id BIGINT NOT NULL REFERENCES public.users(user_id) ON DELETE RESTRICT,
  reason VARCHAR(24) NOT NULL CHECK (reason IN ('abuse','privacy','false_claim','other')),
  description VARCHAR(300) NOT NULL DEFAULT '',
  status VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','dismissed','actioned')),
  resolved_by BIGINT REFERENCES public.users(user_id) ON DELETE SET NULL,
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_review_report_user UNIQUE(review_id,reporter_id)
);
CREATE INDEX idx_review_reports_pending ON public.collaboration_review_report(created_at DESC)
  WHERE status='pending';


-- Existing notifications deliver a first-party reminder as soon as a collaboration
-- automatically completes. No new route or private request metadata is exposed.
ALTER TABLE public.notification DROP CONSTRAINT ck_notification_type;
ALTER TABLE public.notification ADD CONSTRAINT ck_notification_type CHECK (type IN (
  'request_received','request_accepted','request_rejected','request_canceled',
  'request_expired','collab_started','review_ready'
));

-- Explicitly block Supabase/PostgREST direct access. All writes use JWT-checked FastAPI.
ALTER TABLE public.collaboration_review ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.collaboration_review_report ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.collaboration_review,public.collaboration_review_report FROM PUBLIC;
DO $permissions$ DECLARE role_name TEXT; BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
      EXECUTE format('REVOKE ALL ON public.collaboration_review FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON public.collaboration_review_report FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.collaboration_review_review_id_seq FROM %I',role_name);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.collaboration_review_report_report_id_seq FROM %I',role_name);
    END IF;
  END LOOP;
END $permissions$;

-- Local Docker bootstrap follows earlier init scripts; Alembic owns remote migrations.
UPDATE public.insight_alembic_version SET version_num = '20261031_21'
WHERE version_num = '20261029_20';

COMMIT;
