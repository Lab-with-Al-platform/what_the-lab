-- 협업 요청(연구회원 → AI 전문가)에 필요한 테이블입니다. (PostgreSQL) 001, 004, 006 다음에 실행됩니다.
-- 화면: 요청관리 (연구회원은 보낸 요청, AI 전문가는 받은 요청)
-- 같은 내용이 Supabase용 backend/migrations/sql/20261022_03/ 에도 있습니다. 둘을 함께 고칩니다.

-- 1) 협업 요청: research 1 : N, expert 1 : N
--    보낸 연구회원은 research.user_id 로 알 수 있어서 따로 저장하지 않습니다.
CREATE TABLE collaboration_request (
  request_id     BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  research_id    BIGINT        NOT NULL,                                -- 어떤 연구로 보냈나 (research)
  expert_id      BIGINT        NOT NULL,                                -- 받은 AI 전문가 (expert.user_id)
  status         VARCHAR(20)   NOT NULL  DEFAULT 'pending',             -- pending / accepted / started / rejected / expired / canceled
  start_date     DATE          NOT NULL,                                -- 희망 시작일
  end_date       DATE          NOT NULL,                                -- 희망 종료일
  message        VARCHAR(1000) NOT NULL,                                -- 연구회원이 쓴 메시지
  reply_message  VARCHAR(200)  NULL,                                    -- 전문가가 수락하며 남긴 한마디 (선택)
  reject_reason  VARCHAR(20)   NULL,                                    -- schedule / field_mismatch / data_terms / other
  reject_text    VARCHAR(200)  NULL,                                    -- 거절하며 남긴 말 (선택)
  expires_at     TIMESTAMPTZ   NOT NULL  DEFAULT now() + INTERVAL '7 days', -- 이때까지 답이 없으면 만료
  responded_at   TIMESTAMPTZ   NULL,                                    -- 전문가가 수락·거절한 때
  started_at     TIMESTAMPTZ   NULL,                                    -- 연구회원이 협업 시작을 확정한 때
  created_at     TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  updated_at     TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration_request PRIMARY KEY (request_id),
  CONSTRAINT fk_request_research FOREIGN KEY (research_id) REFERENCES research(research_id) ON DELETE CASCADE,
  CONSTRAINT fk_request_expert FOREIGN KEY (expert_id) REFERENCES expert(user_id) ON DELETE CASCADE,
  -- 정해진 값만 들어가게 DB에서도 한 번 더 막습니다. (API에서 먼저 검사)
  CONSTRAINT ck_request_status CHECK (status IN ('pending', 'accepted', 'started', 'rejected', 'expired', 'canceled')),
  CONSTRAINT ck_request_reject_reason CHECK (reject_reason IS NULL OR reject_reason IN ('schedule', 'field_mismatch', 'data_terms', 'other')),
  CONSTRAINT ck_request_period CHECK (end_date >= start_date)
);

-- 같은 연구로 같은 전문가에게 동시에 두 번 보낼 수 없어요.
-- 거절당한 전문가에게도 같은 연구로 다시 보낼 수 없어요. (만료·취소된 요청은 다시 보낼 수 있음)
CREATE UNIQUE INDEX uq_request_research_expert ON collaboration_request (research_id, expert_id)
  WHERE status IN ('pending', 'accepted', 'started', 'rejected');

CREATE INDEX idx_request_expert ON collaboration_request (expert_id);  -- 전문가의 받은 요청 목록
CREATE INDEX idx_request_research ON collaboration_request (research_id);  -- 연구회원의 보낸 요청 목록

CREATE TRIGGER trg_collaboration_request_updated_at BEFORE UPDATE ON collaboration_request
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();