CREATE TABLE collaboration_task_event (
  event_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY,
  task_id     BIGINT        NOT NULL,                  -- 어느 요청
  actor_id    BIGINT        NOT NULL,                  -- 누가 (users.user_id)
  kind        VARCHAR(12)   NOT NULL,                  -- 무엇을 (아래 ck_task_event_kind)
  old_due     DATE          NULL,                      -- 바꾸기 전 기한 (기한 변경 · 다시 요청)
  new_due     DATE          NULL,                      -- 바꾼 기한 / 원하는 기한 (기한 얘기하기)
  note        VARCHAR(200)  NULL,                      -- 이유 (기한 얘기하기 · 다시 요청)
  source      VARCHAR(10)   NOT NULL  DEFAULT 'web',   -- 어디서: web / discord
  created_at  TIMESTAMPTZ   NOT NULL  DEFAULT now(),
  CONSTRAINT pk_collaboration_task_event PRIMARY KEY (event_id),
  CONSTRAINT fk_task_event_task FOREIGN KEY (task_id) REFERENCES collaboration_task(task_id) ON DELETE CASCADE,
  CONSTRAINT fk_task_event_actor FOREIGN KEY (actor_id) REFERENCES users(user_id) ON DELETE RESTRICT,
  CONSTRAINT ck_task_event_kind CHECK (kind IN (
    'created',   -- 요청 남김 (보낸 사람)
    'done',      -- 완료 (받은 사람)
    'canceled',  -- 취소 (보낸 사람)
    'reopened',  -- 되돌리기 (끝낸 사람)
    'due',       -- 기한 변경 (보낸 사람) old_due → new_due
    'due_talk',  -- 기한 얘기하기 (받은 사람) new_due = 원하는 기한(없으면 "어려워요"), note = 이유
    'returned'   -- 다시 요청 (보낸 사람, 완료된 요청을 다시 진행 중으로) note = 이유
  )),
  CONSTRAINT ck_task_event_note CHECK (kind NOT IN ('due_talk', 'returned') OR note IS NOT NULL),  -- 이유는 꼭
  CONSTRAINT ck_task_event_source CHECK (source IN ('web', 'discord'))
);

CREATE INDEX idx_task_event_task ON collaboration_task_event (task_id, event_id);  -- 요청 하나의 기록 (순서대로)

