-- 회원 정지·해제의 성공 기록만 남깁니다. 공용 DB의 Alembic 20261026_08과 같은 구조입니다.
-- 기록 행은 복사하지 않습니다. 브라우저 역할은 직접 읽거나 쓰지 않습니다.
CREATE TABLE public.operation_audit (
    audit_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    idempotency_key   VARCHAR(36)  NOT NULL,
    actor_user_id     BIGINT       NOT NULL,
    target_type       VARCHAR(20)  NOT NULL,
    target_id         VARCHAR(32)  NOT NULL,
    action            VARCHAR(20)  NOT NULL,
    before_status     VARCHAR(20)  NOT NULL,
    after_status      VARCHAR(20)  NOT NULL,
    reason            VARCHAR(200) NOT NULL,
    notice            VARCHAR(200) NOT NULL DEFAULT '',
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_operation_audit PRIMARY KEY (audit_id),
    CONSTRAINT uq_operation_audit_key UNIQUE (idempotency_key),
    CONSTRAINT ck_operation_audit_action CHECK (action IN ('suspend', 'restore')),
    CONSTRAINT ck_operation_audit_target CHECK (target_type IN ('member'))
);
CREATE INDEX ix_operation_audit_target ON public.operation_audit (target_type, target_id, created_at DESC);

ALTER TABLE public.operation_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.operation_audit FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.operation_audit_audit_id_seq FROM PUBLIC;

DO $protect$
DECLARE role_name TEXT;
BEGIN
    FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
            EXECUTE format('REVOKE ALL ON TABLE public.operation_audit FROM %I', role_name);
            EXECUTE format('REVOKE ALL ON SEQUENCE public.operation_audit_audit_id_seq FROM %I', role_name);
        END IF;
    END LOOP;
END $protect$;
